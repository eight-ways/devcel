//! C# (Unity) code generation backend.
//!
//! Imports the `devcel-runtime` C ABI with `DllImport` and generates typed
//! `XxxTable` / `XxxRow` wrappers for each table. Rows are `readonly struct` values
//! that read native buffers directly with one FFI call per value (aiming for zero GC).

use super::{CgColumn, CgModel};
use crate::types::ValueType;

/// Default C# namespace.
pub const DEFAULT_NAMESPACE: &str = "Devcel.Generated";

/// Generate C# source from the model, using `namespace_name` for its namespace
/// (to avoid collisions between projects).
pub fn generate(model: &CgModel, namespace_name: &str) -> String {
    generate_with_class_name(model, namespace_name, "DevcelDatabase")
}

/// Only the database owner type is configurable; table/row/interface names stay schema-derived.
pub fn generate_with_class_name(model: &CgModel, namespace_name: &str, class_name: &str) -> String {
    let mut s = String::new();

    s.push_str("// <auto-generated>\n");
    s.push_str(
        "// Devcel codegen — This file is generated automatically. Do not edit it by hand.\n",
    );
    // Project display names are arbitrary text, never source-code lines.
    s.push_str(&format!(
        "// project: {}\n",
        model
            .project_name
            .replace(['\r', '\n', '\u{0085}', '\u{2028}', '\u{2029}'], " ")
    ));
    s.push_str("// </auto-generated>\n");
    s.push_str("#nullable enable\n");
    s.push_str("using System;\n");
    s.push_str("using System.Collections.Generic;\n");
    s.push_str("using System.IO;\n");
    s.push_str("using System.Runtime.InteropServices;\n\n");
    s.push_str(&format!("namespace {namespace_name}\n{{\n"));

    emit_native(&mut s);
    emit_scalar_parsers(&mut s);
    emit_select_enums(&mut s, model);
    emit_table_reference(&mut s, model, namespace_name, class_name);
    for iface in &model.interfaces {
        emit_interface(&mut s, iface);
        emit_interface_reference(&mut s, model, iface, namespace_name, class_name);
    }
    for table in &model.tables {
        emit_table(&mut s, table, namespace_name, class_name);
        emit_record_reference(&mut s, table, namespace_name, class_name);
    }
    super::csharp_managed::emit(&mut s, model, namespace_name, class_name);
    emit_database(&mut s, model, namespace_name, class_name);

    s.push_str("}\n");
    s
}

/// Emit FFI bindings.
fn emit_native(s: &mut String) {
    s.push_str(
        r#"    internal static class DevcelNative
    {
        // iOS and WebGL Players statically link the runtime into the Player.
#if (UNITY_IOS || UNITY_WEBGL) && !UNITY_EDITOR
        const string DLL = "__Internal";
#else
        const string DLL = "devcel_runtime";
#endif

        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern uint devcel_rt_api_version();
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] private static extern IntPtr devcel_rt_row_uuid(IntPtr db, int table, int row, out int length);
        internal static string RowUuid(IntPtr db, int table, int row)
        {
            var pointer = devcel_rt_row_uuid(db, table, row, out int length);
            return pointer == IntPtr.Zero ? string.Empty : Marshal.PtrToStringUTF8(pointer, length)!;
        }

        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] private static extern int devcel_rt_record_reference_table(IntPtr db, [MarshalAs(UnmanagedType.LPUTF8Str)] string tableUuid, [MarshalAs(UnmanagedType.LPUTF8Str)] string requiredInterface);
        internal static int ResolveRecordTable(IntPtr db, string tableUuid, string requiredInterface)
        {
            try { return devcel_rt_record_reference_table(db, tableUuid, requiredInterface); }
            catch (EntryPointNotFoundException error) { throw new InvalidOperationException("This generated reference requires an updated Devcel native runtime", error); }
        }

        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_get_color32(IntPtr db, int table, int row, int col, out DevcelColor32 value);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_get_color_float(IntPtr db, int table, int row, int col, out DevcelColorFloat value);
        internal static void VerifyApi()
        {
            uint version;
            try { version = devcel_rt_api_version(); }
            catch (EntryPointNotFoundException error)
            { throw new InvalidOperationException("Devcel runtime ABI version 1 is required; update the native runtime and regenerate the SDK", error); }
            if (version != 1) throw new InvalidOperationException("Devcel runtime ABI version 1 is required");
        }
        internal static DevcelColor32 GetColor32(IntPtr db, int table, int row, int col)
        {
            if (devcel_rt_get_color32(db, table, row, col, out var value) != 1)
                throw new InvalidOperationException("Devcel Color32 cell is missing or has a different type");
            return value;
        }
        internal static DevcelColorFloat GetColorFloat(IntPtr db, int table, int row, int col)
        {
            if (devcel_rt_get_color_float(db, table, row, col, out var value) != 1)
                throw new InvalidOperationException("Devcel ColorFloat cell is missing or has a different type");
            return value;
        }
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern IntPtr devcel_rt_open([MarshalAs(UnmanagedType.LPUTF8Str)] string path);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern IntPtr devcel_rt_open_from_json([MarshalAs(UnmanagedType.LPUTF8Str)] string json);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern void devcel_rt_close(IntPtr db);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_reload_if_changed(IntPtr db);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_table_index(IntPtr db, [MarshalAs(UnmanagedType.LPUTF8Str)] string name);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_row_count(IntPtr db, int table);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_column_index(IntPtr db, int table, [MarshalAs(UnmanagedType.LPUTF8Str)] string name);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_row_by_uuid(IntPtr db, int table, [MarshalAs(UnmanagedType.LPUTF8Str)] string uuid);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_get_i32(IntPtr db, int table, int row, int col);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern long devcel_rt_get_i64(IntPtr db, int table, int row, int col);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern float devcel_rt_get_f32(IntPtr db, int table, int row, int col);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern double devcel_rt_get_f64(IntPtr db, int table, int row, int col);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_resolve_table_ref(IntPtr db, int table, int row, int col, [MarshalAs(UnmanagedType.LPUTF8Str)] string requiredInterface);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern double devcel_rt_sample_curve(IntPtr db, int table, int row, int col, double x);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern int devcel_rt_get_bool(IntPtr db, int table, int row, int col);
        [DllImport(DLL, CallingConvention = CallingConvention.Cdecl)] internal static extern IntPtr devcel_rt_get_str(IntPtr db, int table, int row, int col, out int len);

        internal static string GetString(IntPtr db, int table, int row, int col)
        {
            IntPtr ptr = devcel_rt_get_str(db, table, row, col, out int len);
            if (ptr == IntPtr.Zero || len <= 0) return string.Empty;
            return Marshal.PtrToStringUTF8(ptr, len) ?? string.Empty;
        }
    }

"#,
    );
}

/// Emit interface definitions.
fn emit_interface(s: &mut String, iface: &super::CgInterface) {
    s.push_str(&format!(
        "    public interface I{}\n    {{\n",
        iface.type_name
    ));
    for m in &iface.members {
        let ty = member_prop_type(&m.value_type, m.reference_target.as_deref());
        s.push_str(&format!("        {ty} {} {{ get; }}\n", m.accessor));
        if m.value_type == ValueType::TableRef {
            s.push_str(&format!(
                "        DevcelTableReference? {}Table {{ get; }}\n",
                m.accessor
            ));
        }
        if m.value_type == ValueType::DateTime {
            s.push_str(&format!(
                "        DateTimeOffset? {}Rfc3339 {{ get; }}\n",
                m.accessor
            ));
        }
        if m.value_type == ValueType::Curve {
            s.push_str(&format!("        double Sample{}(double x);\n", m.accessor));
        }
    }
    s.push_str("    }\n\n");
}

/// Emit table accessor types and row types.
fn emit_table(s: &mut String, table: &super::CgTable, namespace_name: &str, class_name: &str) {
    let root_type = format!("global::{namespace_name}.{class_name}");
    let base = &table.type_base;

    // --- Table accessors ---
    s.push_str(&format!("    public sealed class {base}Table\n    {{\n"));
    s.push_str(
        &"        public readonly DevcelDatabase Database;\n".replace("DevcelDatabase", &root_type),
    );
    s.push_str("        internal IntPtr Db => Database.CheckedHandle(Database.Generation);\n        internal IntPtr DbAt(long generation) => Database.CheckedHandle(generation);\n");
    s.push_str("        internal int TableIndex;\n");
    for col in &table.columns {
        s.push_str(&format!("        internal int {};\n", col_index_field(col)));
    }
    s.push_str(&format!(
        "\n        internal {base}Table({root_type} db)\n        {{\n"
    ));
    s.push_str("            Database = db;\n            Refresh();\n        }\n\n        internal void Refresh()\n        {\n            var db = Database;\n");
    s.push_str(&format!(
        "            TableIndex = DevcelNative.devcel_rt_table_index(db.Handle, \"{}\");\n",
        escape(&table.data_name)
    ));
    for col in &table.columns {
        s.push_str(&format!(
            "            {} = TableIndex < 0 ? -1 : DevcelNative.devcel_rt_column_index(db.Handle, TableIndex, \"{}\");\n",
            col_index_field(col),
            escape(&col.key)
        ));
    }
    s.push_str("        }\n\n");
    s.push_str("        public int Count => TableIndex < 0 ? 0 : DevcelNative.devcel_rt_row_count(Db, TableIndex);\n");
    s.push_str(&format!(
        "        public {base}Row this[int row] {{ get {{ if (row < 0 || row >= Count) throw new ArgumentOutOfRangeException(nameof(row)); return new {base}Row(this, row); }} }}\n"
    ));
    s.push_str(&format!(
        "        public {base}Row? ById(string uuid)\n        {{\n            int r = DevcelNative.devcel_rt_row_by_uuid(Db, TableIndex, uuid);\n            return r < 0 ? ({base}Row?)null : new {base}Row(this, r);\n        }}\n"
    ));
    s.push_str(&format!(
        "        public IEnumerable<{base}Row> All\n        {{\n            get {{ int c = Count; for (int i = 0; i < c; i++) yield return this[i]; }}\n        }}\n"
    ));
    s.push_str("    }\n\n");

    // --- Row ---
    let impls = if table.csharp_interfaces.is_empty() {
        String::new()
    } else {
        let list: Vec<String> = table
            .csharp_interfaces
            .iter()
            .map(|(i, _)| format!("I{i}"))
            .collect();
        format!(" : {}", list.join(", "))
    };
    s.push_str(&format!(
        "    public readonly struct {base}Row{impls}\n    {{\n"
    ));
    s.push_str(&format!("        readonly {base}Table _t;\n"));
    s.push_str("        readonly int _row;\n        readonly long _generation;\n");
    s.push_str(&format!(
        "        internal {base}Row({base}Table t, int row) {{ _t = t; _row = row; _generation = t.Database.Generation; }}\n\n"
    ));
    s.push_str("        internal string __DevcelRecordId => DevcelNative.RowUuid(_t.DbAt(_generation), _t.TableIndex, _row);\n");
    s.push_str("        public int RowIndex { get { _t.DbAt(_generation); return _row; } }\n");
    for col in &table.columns {
        emit_column_accessor(s, col, namespace_name);
        emit_select_accessor(s, table, col);
    }
    for (iface, bindings) in &table.csharp_interfaces {
        for (member, column) in bindings {
            let ty = member_prop_type(&column.value_type, column.reference_target.as_deref());
            let accessor = &column.accessor;
            s.push_str(&format!("        {ty} I{iface}.{member} => {accessor};\n"));
            match column.value_type {
                ValueType::TableRef => s.push_str(&format!(
                    "        DevcelTableReference? I{iface}.{member}Table => {accessor}Table;\n"
                )),
                ValueType::DateTime => s.push_str(&format!(
                    "        DateTimeOffset? I{iface}.{member}Rfc3339 => {accessor}Rfc3339;\n"
                )),
                ValueType::Curve => s.push_str(&format!(
                    "        double I{iface}.Sample{member}(double x) => Sample{accessor}(x);\n"
                )),
                _ => {}
            }
        }
    }
    s.push_str("    }\n\n");
}

/// Emit an accessor (property) for one column.
fn emit_column_accessor(s: &mut String, col: &CgColumn, namespace_name: &str) {
    let idx = col_index_field(col);
    let access = "_t.DbAt(_generation), _t.TableIndex, _row, _t.".to_string() + &idx;

    if col.value_type == ValueType::Reference {
        match &col.reference_target {
            Some(target) => {
                s.push_str(&format!(
                    "        public {target}Row? {} \n        {{\n            get {{ string __u = DevcelNative.GetString({access}); return string.IsNullOrEmpty(__u) ? ({target}Row?)null : _t.Database.{target}.ById(__u); }}\n        }}\n",
                    col.accessor
                ));
            }
            None => {
                // Return the raw UUID string if the reference cannot be resolved
                s.push_str(&format!(
                    "        public string {} => DevcelNative.GetString({access});\n",
                    col.accessor
                ));
            }
        }
        return;
    }

    if col.value_type == ValueType::TableRef {
        s.push_str(&format!("        public DevcelTableReference? {}Table {{ get {{ int target = DevcelNative.devcel_rt_resolve_table_ref({access}, \"{}\"); return target < 0 ? (DevcelTableReference?)null : new DevcelTableReference(_t.Database, target, _generation); }} }}\n", col.accessor, escape(col.table_ref_interface.as_deref().unwrap_or(""))));
    }
    if col.value_type == ValueType::Curve {
        s.push_str(&format!("        public double Sample{}(double x) => DevcelNative.devcel_rt_sample_curve({access}, x);\n", col.accessor));
    }
    {
        let (kind, suffix, ty) = (ValueType::DateTime, "Rfc3339", "DateTimeOffset");
        if col.value_type == kind {
            s.push_str(&format!("        public {ty}? {0}{suffix} => global::{namespace_name}.DevcelScalarParsers.TryParse{suffix}({0}, out var value) ? value : ({ty}?)null;\n", col.accessor));
        }
    }
    let ty = scalar_prop_type(&col.value_type);
    let expr = scalar_getter_expr(&col.value_type, &access);
    s.push_str(&format!(
        "        public {ty} {} => {expr};\n",
        col.accessor
    ));
}

/// Emit the top-level `DevcelDatabase`.
fn emit_database(s: &mut String, model: &CgModel, namespace_name: &str, class_name: &str) {
    let root_type = format!("global::{namespace_name}.{class_name}");
    s.push_str(
        &"    public sealed class DevcelDatabase : IDisposable\n#if UNITY_5_3_OR_NEWER\n        , global::Devcel.Unity.IDevcelReloadableDatabase\n#endif\n    {\n"
            .replace("DevcelDatabase", class_name),
    );
    s.push_str("        public IntPtr Handle { get; private set; }\n        internal long Generation { get; private set; }\n");
    s.push_str(&r#"        static readonly object RegistryLock = new object();
        static readonly List<WeakReference<DevcelDatabase>> OpenDatabases = new List<WeakReference<DevcelDatabase>>();
        string? _path;
        internal readonly object ReadGate = new object();

        /// <summary>Reload live Open(path) instances for this absolute bundle path. Returns the changed instance count.
        /// Call on the same thread used to access rows; rows are invalidated when their database reloads.</summary>
        public static int ReloadOpenDatabases(string absolutePath)
        {
            if (string.IsNullOrWhiteSpace(absolutePath) || !Path.IsPathFullyQualified(absolutePath))
                throw new ArgumentException("An absolute bundle path is required", nameof(absolutePath));
            string path = Path.GetFullPath(absolutePath);
            var comparison = Path.DirectorySeparatorChar == '\\' ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;
            int changed = 0;
            List<Exception>? failures = null;
            lock (RegistryLock)
            {
                for (int i = OpenDatabases.Count - 1; i >= 0; --i)
                {
                    if (!OpenDatabases[i].TryGetTarget(out var db) || db.Handle == IntPtr.Zero)
                    { OpenDatabases.RemoveAt(i); continue; }
                    if (!string.Equals(path, db._path, comparison)) continue;
                    try { if (db.ReloadIfChanged()) ++changed; }
                    catch (Exception e) { (failures ?? (failures = new List<Exception>())).Add(e); }
                }
            }
            if (failures != null) throw new AggregateException("Devcel: one or more open bundles could not reload", failures);
            return changed;
        }

        internal IntPtr CheckedHandle(long generation)
        {
            if (Handle == IntPtr.Zero) throw new ObjectDisposedException(nameof(DevcelDatabase));
            if (generation != Generation) throw new InvalidOperationException("Devcel row was invalidated by reload; obtain it again by ID");
            return Handle;
        }
"#.replace("DevcelDatabase", &root_type));
    for table in &model.tables {
        s.push_str(&format!(
            "        public {0}Table {0} {{ get; }}\n",
            table.type_base
        ));
    }
    super::csharp_managed::emit_database(s, model);
    s.push_str("        void RefreshTables() {\n");
    for table in &model.tables {
        s.push_str(&format!("            {}.Refresh();\n", table.type_base));
    }
    s.push_str("        }\n");
    s.push_str(&"\n        private DevcelDatabase(IntPtr handle, string? path = null)\n        {\n            Handle = handle;\n            _path = path;\n".replace("DevcelDatabase", class_name));
    for table in &model.tables {
        s.push_str(&format!(
            "            {0} = new {0}Table(this);\n",
            table.type_base
        ));
    }
    s.push_str("            PublishReadModel();\n        }\n\n");
    s.push_str(&r#"        public static DevcelDatabase Open(string path)
        {
            DevcelNative.VerifyApi();
            string absolutePath = Path.GetFullPath(path);
            IntPtr h = DevcelNative.devcel_rt_open(absolutePath);
            if (h == IntPtr.Zero) throw new InvalidOperationException("Devcel: failed to open bundle: " + path);
            var db = new DevcelDatabase(h, absolutePath);
            lock (RegistryLock)
            {
                OpenDatabases.RemoveAll(entry => !entry.TryGetTarget(out var live) || live.Handle == IntPtr.Zero);
                OpenDatabases.Add(new WeakReference<DevcelDatabase>(db));
            }
            return db;
        }

        public static DevcelDatabase FromJson(string json)
        {
            DevcelNative.VerifyApi();
            IntPtr h = DevcelNative.devcel_rt_open_from_json(json);
            if (h == IntPtr.Zero) throw new InvalidOperationException("Devcel: failed to parse bundle JSON");
            return new DevcelDatabase(h);
        }

        /// <summary>Reload changes. Existing rows become invalid; reacquire them by ID.</summary>
        public bool ReloadIfChanged()
        {
            lock (RegistryLock) lock (ReadGate) return ReloadCore();
        }

        bool ReloadCore()
        {
            int result = DevcelNative.devcel_rt_reload_if_changed(CheckedHandle(Generation));
            if (result < 0) throw new InvalidOperationException("Devcel bundle reload failed; previous data was retained");
            if (result == 0 && _readFailure == null) return false;
            if (result != 0) ++Generation;
"#.replace("DevcelDatabase", &root_type));
    for t in &model.tables {
        s.push_str(&format!("            {}.Refresh();\n", t.type_base));
    }
    s.push_str(&r#"            PublishReadModel();
            return true;
        }

#if UNITY_5_3_OR_NEWER
        public bool TryReplaceDatabase(IDisposable candidate)
        {
            if (!(candidate is DevcelDatabase replacement) || ReferenceEquals(replacement, this)) return false;
            lock (RegistryLock) lock (ReadGate) lock (replacement.ReadGate)
            {
                CheckedHandle(Generation); replacement.CheckedHandle(replacement.Generation);
                var previous = Handle;
                Handle = replacement.Handle; _path = replacement._path;
                replacement.Handle = IntPtr.Zero; ++replacement.Generation; ++Generation;
                try
                {
                    RefreshTables();
                    PublishReadModel();
                }
                catch
                {
                    // Ownership has transferred. Close both resources and fail closed;
                    // neither owner may expose partially published data or double-close.
                    DevcelNative.devcel_rt_close(Handle);
                    Handle = IntPtr.Zero; ++Generation;
                    DisposeReadModel(); replacement.DisposeReadModel();
                    OpenDatabases.RemoveAll(entry => !entry.TryGetTarget(out var live) || ReferenceEquals(live, this) || ReferenceEquals(live, replacement));
                    GC.SuppressFinalize(replacement);
                    throw;
                }
                finally { DevcelNative.devcel_rt_close(previous); }
                OpenDatabases.RemoveAll(entry => !entry.TryGetTarget(out var live) || ReferenceEquals(live, replacement));
                OpenDatabases.RemoveAll(entry => entry.TryGetTarget(out var live) && ReferenceEquals(live, this));
                if (_path != null) OpenDatabases.Add(new WeakReference<DevcelDatabase>(this));
                replacement.DisposeReadModel();
                GC.SuppressFinalize(replacement);
                return true;
            }
        }
#endif
        ~DevcelDatabase() { Dispose(); }
        public void Dispose()
        {
            lock (RegistryLock) lock (ReadGate)
            {
                if (Handle != IntPtr.Zero) { DevcelNative.devcel_rt_close(Handle); Handle = IntPtr.Zero; ++Generation; }
                DisposeReadModel();
                OpenDatabases.RemoveAll(entry => !entry.TryGetTarget(out var live) || ReferenceEquals(live, this));
            }
            GC.SuppressFinalize(this);
        }
    }
"#.replace("DevcelDatabase", class_name));
}

/// Field name for a cached column index.
pub(super) fn col_index_field(col: &CgColumn) -> String {
    format!("Col{}", col.accessor)
}

/// Property type for an interface member.
pub(super) fn member_prop_type(vt: &ValueType, reference_target: Option<&str>) -> String {
    if *vt == ValueType::Reference {
        match reference_target {
            Some(t) => format!("{t}Row?"),
            None => "string".to_string(),
        }
    } else {
        scalar_prop_type(vt)
    }
}

/// C# property type for a scalar.
fn scalar_prop_type(vt: &ValueType) -> String {
    match vt {
        ValueType::Color32 => "DevcelColor32".to_string(),
        ValueType::ColorFloat => "DevcelColorFloat".to_string(),
        ValueType::Boolean => "bool".to_string(),
        ValueType::F32 => "float".to_string(),
        ValueType::F64 => "double".to_string(),
        ValueType::U8
        | ValueType::I8
        | ValueType::U16
        | ValueType::I16
        | ValueType::U32
        | ValueType::I32
        | ValueType::U64
        | ValueType::I64 => vt.csharp_type().to_string(),
        // String-like values (String/Select/DateTime/Curve/None/unresolved Reference)
        _ => "string".to_string(),
    }
}

/// C# expression for reading a scalar. `access` contains the arguments "db, table, row, colField".
fn scalar_getter_expr(vt: &ValueType, access: &str) -> String {
    match vt {
        ValueType::Color32 => format!("DevcelNative.GetColor32({access})"),
        ValueType::ColorFloat => format!("DevcelNative.GetColorFloat({access})"),
        ValueType::Boolean => format!("DevcelNative.devcel_rt_get_bool({access}) != 0"),
        ValueType::F32 => format!("DevcelNative.devcel_rt_get_f32({access})"),
        ValueType::F64 => format!("DevcelNative.devcel_rt_get_f64({access})"),
        // Integers that fit in i32
        ValueType::U8 | ValueType::I8 | ValueType::U16 | ValueType::I16 | ValueType::I32 => {
            let cast = vt.csharp_type();
            if cast == "int" {
                format!("DevcelNative.devcel_rt_get_i32({access})")
            } else {
                format!("({cast})DevcelNative.devcel_rt_get_i32({access})")
            }
        }
        // Integers handled as i64
        ValueType::U32 | ValueType::I64 | ValueType::U64 => {
            let cast = vt.csharp_type();
            if cast == "long" {
                format!("DevcelNative.devcel_rt_get_i64({access})")
            } else if cast == "ulong" {
                format!("unchecked((ulong)DevcelNative.devcel_rt_get_i64({access}))")
            } else {
                format!("({cast})DevcelNative.devcel_rt_get_i64({access})")
            }
        }
        // String-like values
        _ => format!("DevcelNative.GetString({access})"),
    }
}

/// Escape characters inside a string literal.
pub(super) fn escape(s: &str) -> String {
    let mut out = String::new();
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            c if c.is_control() || c == '\u{2028}' || c == '\u{2029}' => {
                out.push_str(&format!("\\u{:04X}", c as u32));
            }
            c => out.push(c),
        }
    }
    out
}

/// UUID/interface-validated table reference. Cached references are also invalidated after reload.
fn emit_table_reference(s: &mut String, model: &CgModel, namespace_name: &str, class_name: &str) {
    let root_type = format!("global::{namespace_name}.{class_name}");
    s.push_str(&r#"    public readonly struct DevcelTableReference
    {
        readonly DevcelDatabase _db;
        readonly int _table;
        readonly long _generation;
        internal DevcelTableReference(DevcelDatabase db, int table, long generation)
        { _db = db; _table = table; _generation = generation; }
        public int TableIndex { get { _db.CheckedHandle(_generation); return _table; } }
        public int Count => DevcelNative.devcel_rt_row_count(_db.CheckedHandle(_generation), _table);
"#.replace("DevcelDatabase", &root_type));
    for t in &model.tables {
        s.push_str(&format!("        public {0}Table? As{0}() {{ _db.CheckedHandle(_generation); return _db.{0}.TableIndex == _table ? _db.{0} : null; }}\n", t.type_base));
    }
    s.push_str("    }\n\n");
}

fn emit_select_enums(s: &mut String, model: &CgModel) {
    for table in &model.tables {
        for col in &table.columns {
            if let Some(values) = &col.select_options {
                let ty = super::select_enum_name(table, col);
                s.push_str(&format!("    public enum {ty}\n    {{\n"));
                for (i, member) in super::select_enum_members(&ty, values).iter().enumerate() {
                    s.push_str(&format!("        {member} = {i},\n"));
                }
                s.push_str("    }\n\n");
            }
        }
    }
}

pub(super) fn emit_select_accessor(s: &mut String, table: &super::CgTable, col: &CgColumn) {
    if let Some(values) = &col.select_options {
        let ty = super::select_enum_name(table, col);
        s.push_str(&format!("        public {ty}? {}Value\n        {{\n            get\n            {{\n                switch ({})\n                {{\n", col.accessor, col.accessor));
        for (value, member) in values.iter().zip(super::select_enum_members(&ty, values)) {
            s.push_str(&format!(
                "                    case \"{}\": return {ty}.{member};\n",
                escape(value)
            ));
        }
        s.push_str("                    default: return null;\n                }\n            }\n        }\n");
    }
}

/// Dedicated native RGBA values; DateTime alone retains its opt-in string parser.
fn emit_scalar_parsers(s: &mut String) {
    s.push_str(r#"    /// <summary>Straight-alpha RGBA bytes. No implicit color-space conversion.</summary>
    [StructLayout(LayoutKind.Sequential)]
    public readonly struct DevcelColor32
    {
        public readonly byte R, G, B, A;
        public DevcelColor32(byte r, byte g, byte b, byte a) { R = r; G = g; B = b; A = a; }
        public static DevcelColor32 White => new DevcelColor32(255, 255, 255, 255);
    }

    /// <summary>Finite straight-alpha RGBA. RGB may be negative or above 1; alpha is 0..1.</summary>
    [StructLayout(LayoutKind.Sequential)]
    public readonly struct DevcelColorFloat
    {
        public readonly float R, G, B, A;
        public DevcelColorFloat(float r, float g, float b, float a)
        {
            if (float.IsNaN(r) || float.IsInfinity(r) || float.IsNaN(g) || float.IsInfinity(g) ||
                float.IsNaN(b) || float.IsInfinity(b) || float.IsNaN(a) || float.IsInfinity(a) || a < 0 || a > 1)
                throw new ArgumentOutOfRangeException(nameof(a), "Finite RGB and alpha in 0..1 are required");
            R = r; G = g; B = b; A = a;
        }
        public static DevcelColorFloat White => new DevcelColorFloat(1, 1, 1, 1);
    }

    /// <summary>Opt-in parser for explicitly formatted DateTime strings.</summary>
    public static class DevcelScalarParsers
    {
        private static int Digits(string text, int at, int count)
        {
            int value = 0;
            for (int i = at; i < at + count; ++i)
            {
                char c = text[i];
                if (c < '0' || c > '9') return -1;
                value = value * 10 + c - '0';
            }
            return value;
        }

        /// <summary>RFC3339 subset: YYYY-MM-DD[Tt]hh:mm:ss[.1-7 digits] with Z/z or +/-HH:MM.
        /// Requires a known explicit offset within +/-14:00. Rejects -00:00 (unknown offset), leap seconds,
        /// whitespace, year 0000 and instants outside years 0001-9999. Gregorian dates; 100ns precision.
        /// Never assumes a local timezone or rounds fractions. Other strings remain available through the raw accessor.</summary>
        public static bool TryParseRfc3339(string? text, out DateTimeOffset value)
        {
            value = default;
            if (text == null || text.Length < 20 || text[4] != '-' || text[7] != '-' ||
                (text[10] != 'T' && text[10] != 't') || text[13] != ':' || text[16] != ':') return false;
            int year = Digits(text, 0, 4), month = Digits(text, 5, 2), day = Digits(text, 8, 2);
            int hour = Digits(text, 11, 2), minute = Digits(text, 14, 2), second = Digits(text, 17, 2);
            if (year < 1 || month < 1 || month > 12 || day < 1 || day > DateTime.DaysInMonth(year, month) ||
                hour < 0 || hour > 23 || minute < 0 || minute > 59 || second < 0 || second > 59) return false;
            int pos = 19, ticks = 0;
            if (text[pos] == '.')
            {
                int start = ++pos;
                while (pos < text.Length && text[pos] >= '0' && text[pos] <= '9')
                {
                    if (pos - start == 7) return false;
                    ticks = ticks * 10 + text[pos++] - '0';
                }
                int count = pos - start;
                if (count == 0) return false;
                for (; count < 7; ++count) ticks *= 10;
            }
            if (pos >= text.Length) return false;
            int offsetMinutes = 0;
            if ((text[pos] == 'Z' || text[pos] == 'z') && pos + 1 == text.Length) { }
            else
            {
                if (text.Length - pos != 6 || (text[pos] != '+' && text[pos] != '-') || text[pos + 3] != ':') return false;
                int hours = Digits(text, pos + 1, 2), minutes = Digits(text, pos + 4, 2);
                if (hours < 0 || hours > 14 || minutes < 0 || minutes > 59 || (hours == 14 && minutes != 0)) return false;
                offsetMinutes = hours * 60 + minutes;
                if (text[pos] == '-')
                {
                    if (offsetMinutes == 0) return false;
                    offsetMinutes = -offsetMinutes;
                }
            }
            try
            {
                value = new DateTimeOffset(year, month, day, hour, minute, second, TimeSpan.FromMinutes(offsetMinutes)).AddTicks(ticks);
                return true;
            }
            catch (ArgumentException) { return false; }
        }
    }

"#);
}

/// Validate only C# additions, without changing other language contracts.
pub(super) fn validate_reference_names(model: &CgModel) -> crate::Result<()> {
    use std::collections::HashSet;
    let mut names: HashSet<String> = model
        .tables
        .iter()
        .flat_map(|t| {
            [
                format!("{}Table", t.type_base),
                format!("{}Row", t.type_base),
            ]
        })
        .chain(model.interfaces.iter().map(|i| format!("I{}", i.type_name)))
        .collect();
    for name in [
        "DevcelNative",
        "DevcelTableReference",
        "DevcelColor32",
        "DevcelColorFloat",
        "DevcelScalarParsers",
        "DevcelTableHandle",
    ] {
        names.insert(name.into());
    }
    for table in &model.tables {
        for column in &table.columns {
            if column.select_options.is_some() {
                names.insert(super::select_enum_name(table, column));
            }
        }
    }
    for iface in &model.interfaces {
        for member in &iface.members {
            if [
                "Exists",
                "Uuid",
                "TableUuid",
                "ResolutionCount",
                "RequireCurrent",
                "EnsureCurrent",
            ]
            .contains(&member.accessor.as_str())
                || member.accessor == format!("I{}Handle", iface.type_name)
            {
                return Err(crate::app_error::authoring_error(format!(
                    "Generated C# live interface member collision in {}: {}",
                    iface.type_name, member.accessor
                )));
            }
        }
        for name in [
            format!("I{}Reference", iface.type_name),
            format!("I{}Handle", iface.type_name),
            format!("I{}Key", iface.type_name),
        ] {
            if !names.insert(name.clone()) {
                return Err(crate::app_error::authoring_error(format!(
                    "Generated C# reference type collision: {name}"
                )));
            }
        }
    }
    let mut managed_root_members: HashSet<String> = [
        "TableViews",
        "ShareString",
        "GetTableView",
        "CheckReadModel",
        "PublishReadModel",
        "DisposeReadModel",
        "Array",
        "StringComparer",
    ]
    .into_iter()
    .map(str::to_owned)
    .collect();
    for table in &model.tables {
        for prefix in ["Live", "Retired", "Members"] {
            managed_root_members.insert(format!("{prefix}{}", table.type_base));
        }
    }
    for t in &model.tables {
        if managed_root_members.contains(&t.type_base) {
            return Err(crate::app_error::authoring_error(format!(
                "Generated C# managed root member collision: {}",
                t.type_base
            )));
        }
        for name in [
            format!("{}Reference", t.type_base),
            format!("{}References", t.type_base),
            format!("{}Handle", t.type_base),
            format!("{}Collection", t.type_base),
            format!("{}Key", t.type_base),
        ] {
            if !names.insert(name.clone()) {
                return Err(crate::app_error::authoring_error(format!(
                    "Generated reference type collision: {name}"
                )));
            }
        }
        for column in &t.columns {
            if [
                "Exists",
                "Uuid",
                "TableUuid",
                "ResolutionCount",
                "RequireCurrent",
                "EnsureCurrent",
                "State",
                "Prepare",
                "Publish",
            ]
            .contains(&column.accessor.as_str())
                || column.accessor == format!("{}Handle", t.type_base)
                || t.csharp_interfaces.iter().any(|(name, _)| {
                    column.accessor == format!("Has{name}")
                        || column.accessor == format!("Require{name}")
                })
            {
                return Err(crate::app_error::authoring_error(format!(
                    "Generated C# live handle member collision in {}: {}",
                    t.data_name, column.accessor
                )));
            }
        }
        let mut labels = HashSet::new();
        for (_, label) in &t.labeled_records {
            crate::validate_data_name(label).map_err(|e| {
                crate::app_error::authoring_error(format!(
                    "Invalid record label in {}: {label}: {e}",
                    t.data_name
                ))
            })?;
            const KEYWORDS: &str = "abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while";
            if KEYWORDS.split_whitespace().any(|word| word == label) {
                return Err(crate::app_error::authoring_error(format!(
                    "C# reserved record label in {}: {label}",
                    t.data_name
                )));
            }
            if label == &format!("{}References", t.type_base) || !labels.insert(label) {
                return Err(crate::app_error::authoring_error(format!(
                    "Record label collision in {}: {label}",
                    t.data_name
                )));
            }
        }
    }
    Ok(())
}

fn emit_record_reference(
    s: &mut String,
    table: &super::CgTable,
    namespace: &str,
    class_name: &str,
) {
    let base = &table.type_base;
    let table_uuid = escape(&table.uuid);
    let db = format!("global::{namespace}.{class_name}");
    s.push_str(&format!(
        r#"
    [Serializable]
#if UNITY_5_3_OR_NEWER
    [global::Devcel.Unity.DevcelRecordTarget(typeof({db}), "{table_name}", "{table_uuid}")]
#endif
#if UNITY_EDITOR
"#,
        table_name = escape(&table.data_name),
        table_uuid = escape(&table.uuid)
    ));
    let mut labels = table.labeled_records.clone();
    labels.sort_by(|a, b| (&a.1, &a.0).cmp(&(&b.1, &b.0)));
    for (id, label) in &labels {
        s.push_str(&format!(
            "    [global::Devcel.Unity.DevcelRecordLabel(\"{}\", \"{}\")]\n",
            escape(id),
            escape(label)
        ));
    }
    s.push_str(&format!(
        r#"#endif
    public sealed class {base}Reference
#if UNITY_5_3_OR_NEWER
        : global::Devcel.Unity.DevcelTypedRecordReference
#endif
    {{
#if !UNITY_5_3_OR_NEWER
        private readonly string uuid;
        public string Uuid => uuid;
        public bool IsEmpty => string.IsNullOrEmpty(uuid);
#endif
        public {base}Reference() : this(string.Empty) {{ }}
        public {base}Reference(string uuid)
#if UNITY_5_3_OR_NEWER
            : base(uuid)
#endif
        {{
#if !UNITY_5_3_OR_NEWER
            this.uuid = uuid ?? string.Empty;
#endif
        }}
        internal {base}Row? Resolve({db} database)
        {{
            if (database == null) throw new ArgumentNullException(nameof(database));
            var handle = database.CheckedHandle(database.Generation);
            if (IsEmpty) return null;
            int actualTable = DevcelNative.ResolveRecordTable(handle, "{table_uuid}", string.Empty);
            return actualTable >= 0 && actualTable == database.{base}.TableIndex ? database.{base}.ById(Uuid) : ({base}Row?)null;
        }}
"#
    ));
    for (iface, _) in &table.csharp_interfaces {
        s.push_str(&format!(
            "        public I{iface}Key As{iface}() => new I{iface}Key(\"{}\", Uuid);\n",
            escape(&table.uuid)
        ));
    }
    s.push_str(&format!(
        "    }}\n    public static class {base}References\n    {{\n"
    ));
    for (id, label) in labels {
        s.push_str(&format!(
            "        public static {base}Key {label} => new {base}Key(\"{}\");\n",
            escape(&id)
        ));
    }
    s.push_str("    }\n");
}

